-- =============================================================================
-- 迁移 018：requests 记录真实路由的提供商（2026-10-19 v1.6.30）
--
-- 背景：requests 表此前没有 provider 列，提供商归属靠「模型 id → 生效目录的
-- provider」事后反解，规则是遍历顺序先到先得（listActive = ORDER BY created_at ASC）。
-- 而路由 resolveRoute 的候选顺序是「密钥绑定的提供商优先，其余按创建序」。
--
-- 二者不一致的后果：当一个模型 id 同时存在于两家目录里（生产实测 MiniMax-M2.7 /
-- M3 / M3.1-Flash-Preview 同时在 MiniMax Code 与 Code2 中），若密钥绑定的是
-- **较晚创建**的那家，请求实际路由到 B，统计却记到 A —— 两个都叫「提供商用量」
-- 的数字会对不上，且没有任何字段能发现。
--
-- 一列（增量、可空）：
--   · provider_id TEXT  本次请求实际路由到的提供商 id
--                        NULL = 本迁移之前的老行（未记录）或模型解析前即被本地拒绝
--
-- 为什么不加外键：提供商被删除后，历史统计仍应显示那家曾经的用量；
-- ON DELETE SET NULL 会把归属一起抹掉，反而丢信息。归属是**当时的事实快照**。
--
-- 不设默认值、不回填：老行的真实归属已不可知，按「目录反解」继续兜底是正确的
-- 降级；回填等于把猜测写成事实。
--
-- 幂等：入口按 user_version 短路（17 → 18 只跑一次）。
-- =============================================================================

BEGIN;

ALTER TABLE requests ADD COLUMN provider_id TEXT;

PRAGMA user_version = 18;

COMMIT;
