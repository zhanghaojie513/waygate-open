-- 迁移 021：requests 补 ingress_ms（2026-10-21 v1.7.3）
--
-- 背景（发版当天生产实证的修正）：迁移 020 引入的 `auth_ms` 定义是
-- 「请求进门 → 鉴权完成」，但**「进门」（onRequest）早于 body 解析** ——
-- agent 的 body 常有几十 MB（长会话 + 图片 base64），那段时间是**客户端在上传**。
--
-- 生产实测：auth_ms 出现 2238 / 6744 / 9660ms 且逐次递增 —— 因为 body 越来越大。
-- 把它算进「我方开销」让归因完全反了（这次要解决的正是「谁慢」的问题）。
--
-- 处置：起点改到 **body 解析完成**（Fastify `preHandler`，早于 guard），
-- 并新增 `ingress_ms` 记录「进门 → body 就绪」这一段（客户端侧成本）。
--
--   ingress_ms = bodyReadyAt - arrivedAt   ← 客户端上传 + 解析等待
--   auth_ms    = authed - bodyReadyAt      ← 真正的鉴权耗时（口径已变，见下）
--
-- ⚠️ 口径变更说明：`auth_ms` 的含义在 v1.7.3 变了（从「进门起算」改为「body 就绪起算」）。
--    迁移 020 到 v1.7.2 之间写入的少数行，其 auth_ms 含上传时间 —— 样本极少
--    （v1.7.2 在线约 40 分钟），且这几行的 ingress_ms 为 NULL 可据此识别。
--    **不做回溯改写**：那是改写历史测量值，违反「记录事实」的纪律。
--
-- 幂等：入口按 user_version 短路（20 → 21 只跑一次）。
-- =============================================================================

BEGIN;

ALTER TABLE requests ADD COLUMN ingress_ms INTEGER;

PRAGMA user_version = 21;

COMMIT;
